function pick(arr: string[]): string {
  return arr[Math.floor(Math.random() * arr.length)];
}

/**
 * Generate a readable adjective-noun ID (e.g. "thirsty-oasis").
 * ~110 adjectives × ~130 nouns ≈ 14,000 combinations.
 * Pass existing IDs to avoid collisions; the function retries up to 20 times.
 */
export function generateReadableId(
  existingIds: Set<string> = new Set(),
): string {
  for (let attempt = 0; attempt < 20; attempt++) {
    const id = `${pick(ADJECTIVES)}-${pick(NOUNS)}`;
    if (!existingIds.has(id)) return id;
  }
  // Extremely unlikely fallback: append a short suffix
  return `${pick(ADJECTIVES)}-${pick(NOUNS)}-${Math.random().toString(36).slice(2, 5)}`;
}
